class BlockArt(BaseComponent):
    """块字符 ASCII 艺术渲染器。

    将普通文本转换为基于块字符（██╗ ██║ ╚═╝ 等）的 ASCII 艺术。
    每个字符渲染为 6 行等宽图案。

    Examples:
        >>> art = BlockArt(normal_mode=True)
        >>> result = art.render_text("Hi").render()
        >>> isinstance(result, str) and len(result) > 0
        True
    """

    def __init__(
        self,
        text: str = "",
        char_width: int = 9,
        char_height: int = 6,
        renderer: GradientRenderer | None = None,
        normal_mode: bool = False,
        theme: ThemeConfig | None = None,
    ) -> None:
        """初始化块字符艺术渲染器。

        Args:
            text: 待渲染的文本。
            char_width: 每个字符的宽度（列数），默认 9。
            char_height: 每个字符的高度（行数），固定为 6。
            renderer: 渐变渲染器。
            normal_mode: 正常模式（降级输出）。
            theme: 主题配置。
        """
        super().__init__(renderer=renderer, normal_mode=normal_mode, theme=theme)
        self._text = text
        self._char_width = char_width
        self._char_height = char_height

    def text(self, value: str) -> "BlockArt":
        """设置渲染文本（链式）。

        Args:
            value: 文本内容。

        Returns:
            BlockArt: 自身引用。
        """
        self._text = value
        return self

    def render_text(self, text: str) -> "BlockArt":
        """设置渲染文本（链式别名）。

        Args:
            text: 文本内容。

        Returns:
            BlockArt: 自身引用。
        """
        self._text = text
        return self

    def render(self) -> str:
        """渲染块字符艺术。

        Returns:
            str: 多行 ASCII 艺术字符串。
        """
        if not self._text:
            return ""

        lines: list[list[str]] = [[] for _ in range(self._char_height)]

        for char in self._text:
            pattern = _CHAR_MAP.get(char)
            if pattern is None:
                # 未知字符用空格占位
                pattern = _CHAR_MAP.get(" ", [" "] * self._char_height)

            for row_idx in range(self._char_height):
                cell = pattern[row_idx] if row_idx < len(pattern) else ""
                # 固定宽度对齐
                lines[row_idx].append(cell.ljust(self._char_width))

        return "\n".join("".join(row) for row in lines)

    def build(self) -> str:
        """构建块字符艺术（render 的别名）。

        Returns:
            str: 多行 ASCII 艺术字符串。
        """
        return self.render()
